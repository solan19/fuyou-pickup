    // ==================== 三、加权抽取（防重复） ====================

    /** 最近说过的句子（FIFO，最多记 60 条）—— 在最近窗口内的句子降权 */
    private val recent = ArrayDeque<String>()
    private const val RECENT_MAX = 60
    private const val RECENT_BLOCK = 25   // 最近 25 条内直接避开

    private fun pick(pool: List<String>): String {
        if (pool.isEmpty()) return ""
        val blocked = recent.toList().takeLast(RECENT_BLOCK).toHashSet()
        val fresh = pool.filter { it !in blocked }
        val chosen = if (fresh.isNotEmpty()) fresh.random() else pool.random()
        recent.addLast(chosen)
        while (recent.size > RECENT_MAX) recent.removeFirst()
        return chosen
    }
